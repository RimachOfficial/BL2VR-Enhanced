# Generates stubs.asm / stubs.h / resolve.inl / proxy.def from the ovr export list.
# Run:  powershell -ExecutionPolicy Bypass -File gen_stubs.ps1
param([string]$ExportFile = "C:\Users\Rimach\Desktop\BL2VR-grip\ovr_exports.txt")
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path

$raw = Get-Content -LiteralPath $ExportFile -Raw
$names = ($raw -split '[,\s]+') | Where-Object { $_ -match '^[A-Za-z_]\w*$' } | Select-Object -Unique
if ($names.Count -lt 100) { throw "expected ~128 export names, got $($names.Count)" }
Write-Host "generating for $($names.Count) exports"

# ---- stubs.asm : MASM x64 jump stubs (pass every register straight through) ----
$a = [System.Collections.Generic.List[string]]::new()
$a.Add('; AUTO-GENERATED by gen_stubs.ps1 -- do not edit')
$a.Add('option casemap:none')
$a.Add('.DATA')
foreach ($n in $names) { $a.Add("PUBLIC g_$n"); $a.Add("g_$n QWORD 0") }
$a.Add('.CODE')
foreach ($n in $names) {
  $a.Add("PUBLIC $n")
  $a.Add("$n PROC")
  $a.Add("    jmp qword ptr [g_$n]")
  $a.Add("$n ENDP")
}
$a.Add('END')
Set-Content -LiteralPath "$here\stubs.asm" -Value $a -Encoding ASCII

# ---- stubs.h : the pointer globals, visible to C++ ----
$h = [System.Collections.Generic.List[string]]::new()
$h.Add('// AUTO-GENERATED by gen_stubs.ps1 -- do not edit')
$h.Add('#pragma once')
foreach ($n in $names) { $h.Add("extern `"C`" void* g_$n;") }
Set-Content -LiteralPath "$here\stubs.h" -Value $h -Encoding ASCII

# ---- resolve.inl : one-shot resolution of every export from the real runtime ----
$r = [System.Collections.Generic.List[string]]::new()
$r.Add('// AUTO-GENERATED by gen_stubs.ps1 -- do not edit')
$r.Add('#pragma once')
$r.Add('#define RESOLVE(real, name) g_##name = (void*)GetProcAddress(real, #name);')
$r.Add('#define RESOLVE_ALL(real) \')
for ($i = 0; $i -lt $names.Count; $i++) {
  $suffix = if ($i -eq $names.Count - 1) { '' } else { ' \' }
  $r.Add("    RESOLVE(real, $($names[$i]))$suffix")
}
Set-Content -LiteralPath "$here\resolve.inl" -Value $r -Encoding ASCII

# ---- proxy.def : export every name (plain exports, NOT forwarders) ----
$d = [System.Collections.Generic.List[string]]::new()
$d.Add('; AUTO-GENERATED by gen_stubs.ps1 -- do not edit')
$d.Add('LIBRARY LibOVRRT64_1')
$d.Add('EXPORTS')
foreach ($n in $names) { $d.Add("    $n") }
Set-Content -LiteralPath "$here\proxy.def" -Value $d -Encoding ASCII

Write-Host "wrote stubs.asm, stubs.h, resolve.inl, proxy.def"